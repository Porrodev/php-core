<?php

namespace Porro\Tools\ProbeSources;

use Porro\Core\Activity\Probes;

/**
 * Builds resources/probes/candidates.json: paths from authoritative
 * sources that Probes does not match yet, each with a suggested category,
 * for a person to review. It never touches Probes::PATTERNS.
 *
 * Sources:
 * - OWASP Core Rule Set (Apache-2.0), latest release: restricted-files,
 *   lfi-os-files and scanners-user-agents.
 * - CISA Known Exploited Vulnerabilities, CVEs added in the last 90 days,
 *   with request paths from the matching ProjectDiscovery nuclei template
 *   (MIT), latest release.
 */
final class Generator
{
    public const CRS_REPO = 'coreruleset/coreruleset';

    public const NUCLEI_REPO = 'projectdiscovery/nuclei-templates';

    public const KEV_URL = 'https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json';

    public const KEV_WINDOW_DAYS = 90;

    /** CRS file => the category a path from it defaults to. */
    public const CRS_PATH_FILES = [
        'restricted-files.data' => Probes::FILES,
        'lfi-os-files.data' => Probes::TRAVERSAL,
    ];

    public const CRS_USER_AGENTS = 'scanners-user-agents.data';

    /**
     * Limits on what a source can hand us, well above today's sizes (CRS
     * files have about 1,200 entries, 90 days of KEV about 100 CVEs). Past
     * an entry or CVE limit the run fails, since the source has changed
     * shape; over-long paths and lines are dropped.
     */
    public const MAX_ENTRIES = 5000;

    public const MAX_CVES = 400;

    public const MAX_TEMPLATE_PATHS = 50;

    public const MAX_PATH_LENGTH = 1024;

    public function __construct(
        private readonly Http $http,
        private readonly \DateTimeImmutable $today,
        private readonly Probes $probes = new Probes,
    ) {}

    /**
     * The whole candidates document.
     *
     * @return array<string, mixed>
     */
    public function build(): array
    {
        return [
            'about' => 'Candidate probe paths from public sources that Probes does not match yet. '
                .'Generated by tools/probe-sources.php for review only; nothing reads this at runtime. '
                .'See "Reviewing probe candidates" in README.md.',
            'crs' => $this->crs(),
            'kev' => $this->kev(),
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public function crs(): array
    {
        $tag = $this->latestTag(self::CRS_REPO);
        $files = [];
        $entries = [];

        foreach (self::CRS_PATH_FILES as $file => $default) {
            $url = $this->blobUrl(self::CRS_REPO, $tag, "rules/{$file}");
            $lines = $this->lines($file, $this->fetch($this->rawUrl(self::CRS_REPO, $tag, "rules/{$file}")));
            $covered = 0;

            foreach ($lines as $line) {
                $path = CrsDataFile::toPath($line);

                if ($this->probes->match($path) !== null) {
                    $covered++;

                    continue;
                }

                $entries[] = [
                    'path' => $path,
                    'category' => Categoriser::suggest($path, $default),
                    'file' => $file,
                    'source_url' => $url,
                ];
            }

            $files[$file] = ['source_url' => $url, 'entries' => count($lines), 'covered' => $covered];
        }

        $agents = $this->lines(self::CRS_USER_AGENTS, $this->fetch($this->rawUrl(self::CRS_REPO, $tag, 'rules/'.self::CRS_USER_AGENTS)));

        return [
            'tag' => $tag,
            'license' => 'Apache-2.0',
            'repository' => 'https://github.com/'.self::CRS_REPO,
            'files' => $files,
            'entries' => $this->dedupe($entries),
            // Probes only looks at paths. Kept for a user-agent check later.
            'user_agents' => [
                'source_url' => $this->blobUrl(self::CRS_REPO, $tag, 'rules/'.self::CRS_USER_AGENTS),
                'entries' => $agents,
            ],
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public function kev(): array
    {
        $feed = json_decode($this->fetch(self::KEV_URL), true);

        if (! is_array($feed) || ! isset($feed['catalogVersion'], $feed['vulnerabilities'])) {
            throw new \RuntimeException('The KEV feed is not in the expected shape');
        }

        $since = $this->today->modify('-'.self::KEV_WINDOW_DAYS.' days')->format('Y-m-d');
        $ref = $this->latestTag(self::NUCLEI_REPO);
        $entries = [];
        $noTemplate = [];
        $covered = 0;
        $recent = 0;

        foreach ($feed['vulnerabilities'] as $vuln) {
            $cve = (string) ($vuln['cveID'] ?? '');

            if (($vuln['dateAdded'] ?? '') < $since || ! preg_match('/^CVE-(\d{4})-\d+$/', $cve, $m)) {
                continue;
            }

            if (++$recent > self::MAX_CVES) {
                throw new \RuntimeException('More than '.self::MAX_CVES.' KEV CVEs in '.self::KEV_WINDOW_DAYS.' days; check the feed');
            }

            $file = "http/cves/{$m[1]}/{$cve}.yaml";
            $yaml = $this->http->get($this->rawUrl(self::NUCLEI_REPO, $ref, $file));

            if ($yaml === null) {
                $noTemplate[] = $cve;

                continue;
            }

            $paths = array_filter(NucleiTemplate::paths($yaml), fn (string $p) => strlen($p) <= self::MAX_PATH_LENGTH);

            foreach (array_slice($paths, 0, self::MAX_TEMPLATE_PATHS) as $path) {
                if ($this->probes->match($path) !== null) {
                    $covered++;

                    continue;
                }

                $entries[] = [
                    'path' => $path,
                    'category' => Categoriser::suggest($path, Probes::APPLIANCE, $vuln['vendorProject'] ?? null),
                    'cve' => $cve,
                    'vendor' => $vuln['vendorProject'] ?? null,
                    'product' => $vuln['product'] ?? null,
                    'template' => NucleiTemplate::name($yaml),
                    'date_added' => $vuln['dateAdded'],
                    'source_url' => $this->blobUrl(self::NUCLEI_REPO, $ref, $file),
                ];
            }
        }

        sort($noTemplate);

        return [
            'catalog_version' => $feed['catalogVersion'],
            'catalog_url' => self::KEV_URL,
            'window_days' => self::KEV_WINDOW_DAYS,
            'cves' => $recent,
            'covered' => $covered,
            'nuclei' => [
                'ref' => $ref,
                'license' => 'MIT',
                'repository' => 'https://github.com/'.self::NUCLEI_REPO,
            ],
            'entries' => $this->dedupe($entries),
            'no_template' => $noTemplate,
        ];
    }

    /**
     * A CRS file's entries, without over-long lines, failing past the cap.
     *
     * @return list<string>
     */
    private function lines(string $file, string $contents): array
    {
        $lines = CrsDataFile::parse($contents);

        if (count($lines) > self::MAX_ENTRIES) {
            throw new \RuntimeException("CRS {$file} has more than ".self::MAX_ENTRIES.' entries; check the release');
        }

        // Under, not up to: toPath() adds a slash.
        return array_values(array_filter($lines, fn (string $line) => strlen($line) < self::MAX_PATH_LENGTH));
    }

    /**
     * One entry per path, sorted, so a rerun with the same sources gives
     * the same file.
     *
     * @param  list<array<string, mixed>>  $entries
     * @return list<array<string, mixed>>
     */
    private function dedupe(array $entries): array
    {
        $unique = [];

        foreach ($entries as $entry) {
            $unique[$entry['path']] ??= $entry;
        }

        ksort($unique, SORT_STRING);

        return array_values($unique);
    }

    private function latestTag(string $repo): string
    {
        $release = json_decode($this->fetch("https://api.github.com/repos/{$repo}/releases/latest"), true);
        $tag = is_array($release) ? ($release['tag_name'] ?? null) : null;

        if (! is_string($tag) || ! preg_match('#^[\w.-]+$#', $tag)) {
            throw new \RuntimeException("No usable latest release tag for {$repo}");
        }

        return $tag;
    }

    private function fetch(string $url): string
    {
        return $this->http->get($url) ?? throw new \RuntimeException("{$url} answered 404");
    }

    private function rawUrl(string $repo, string $ref, string $file): string
    {
        return "https://raw.githubusercontent.com/{$repo}/{$ref}/{$file}";
    }

    private function blobUrl(string $repo, string $ref, string $file): string
    {
        return "https://github.com/{$repo}/blob/{$ref}/{$file}";
    }
}
